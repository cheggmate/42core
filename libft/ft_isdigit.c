int ft_isdigit(char *str)
{
	int	is_true;

	is_true = 1;
	if (*str == '\0')
		is_true = 1;
	while (*str)
	{
		if (!(*str >= '0' && *str <= '9'))
			is_true = 0;
		str++;
	}
	return (is_true);
}